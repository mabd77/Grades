"""
مشروع تقدير الطالب
يقوم بتحويل الدرجة العددية إلى تقدير (ضعيف، جيد، جيد جداً، ممتاز)
يتحمل الأخطاء ويستمر حتى يطلب المستخدم الخروج
"""

def get_grade_estimate(score):
    """
    تحويل الدرجة العددية إلى تقدير نصي
    
    المعاملات:
    score (float): درجة الطالب من 0 إلى 100
    
    المخرجات:
    str: التقدير المناسب
    """
    if score < 60:
        return "ضعيف"
    elif score < 75:
        return "جيد"
    elif score < 90:
        return "جيد جداً"
    else:  # 90-100
        return "ممتاز"

def main():
    """الدالة الرئيسية للبرنامج"""
    print("=" * 50)
    print("برنامج تقدير الطالب (ضعيف، جيد، جيد جداً، ممتاز)")
    print("=" * 50)
    print("أدخل درجة الطالب (0-100) أو اكتب 'خروج' لإنهاء البرنامج.\n")
    
    while True:
        # طلب إدخال من المستخدم
        user_input = input("أدخل درجة الطالب: ").strip()
        
        # التحقق من رغبة المستخدم في الخروج
        if user_input.lower() == "خروج":
            print("\nشكراً لاستخدام البرنامج. إلى اللقاء!")
            break
        
        # محاولة تحويل الإدخال إلى رقم
        try:
            score = float(user_input)
        except ValueError:
            print("❌ خطأ: يرجى إدخال رقم صحيح (0-100) أو كلمة 'خروج'.")
            continue
        
        # التحقق من صحة المجال
        if score < 0 or score > 100:
            print("❌ خطأ: الدرجة يجب أن تكون بين 0 و 100 فقط.")
            continue
        
        # حساب التقدير
        estimate = get_grade_estimate(score)
        
        # عرض النتيجة
        print(f"✅ الدرجة: {score} => التقدير: {estimate}\n")

# بدء تنفيذ البرنامج
if __name__ == "__main__":
    main()
